export const notes = [];

export const lessons = RAW.map(l => {
  const items = l.jamo.map(([jamo, roman, tip, ex, key]) => {
    const n = { id: `ko.j.${key || jamo}`, type: 'jamo', deck: 'hangul', dirs: ['read'], jamo, roman, tip, ex };
    notes.push(n);
    return n.id;
  });
  const words = l.words.map(([ko, roman, zh, pron]) => {
    const n = { id: `ko.w.${ko}`, type: 'word', deck: 'hangul', dirs: ['read'], ko, roman, zh, pron };
    notes.push(n);
    return n.id;
  });
  return { id: l.id, title: l.title, intro: l.intro, items, words, contrasts: l.contrasts || [] };
});
